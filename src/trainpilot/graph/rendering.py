"""Deterministic rendering of run files from the TrainingSpec.

The spec is the single source of truth: the RayJob YAML, the training
script and the training config are always regenerated from it with
Jinja2 (StrictUndefined, so a missing value fails loudly instead of
silently rendering empty). Repairs never patch the generated files;
the planner produces a new spec and the coder regenerates everything.
"""
from __future__ import annotations

import hashlib

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined

from ..prompts.loader import prompts_dir
from ..schemas import GeneratedFile, TrainingSpec

_env = Environment(
    loader=FileSystemLoader(str(prompts_dir())),
    undefined=StrictUndefined,
    keep_trailing_newline=True,
)


def content_hash(content: str) -> str:
    return hashlib.sha256(content.encode("utf-8")).hexdigest()[:12]


def render_rayjob_yaml(spec: TrainingSpec, job_name: str, attempt: int,
                       spec_version: int) -> str:
    template = _env.get_template("rayjob.yaml.j2")
    return template.render(
        spec=spec, job_name=job_name, spec_hash=spec.spec_hash(),
        attempt=attempt, spec_version=spec_version,
    )


def render_train_script(spec: TrainingSpec, attempt: int,
                        spec_version: int) -> str:
    template = _env.get_template("train.py.j2")
    return template.render(
        spec=spec, spec_hash=spec.spec_hash(),
        attempt=attempt, spec_version=spec_version,
    )


def render_train_config_yaml(spec: TrainingSpec, attempt: int,
                             spec_version: int) -> str:
    header = (
        f"# spec_hash: {spec.spec_hash()} attempt: {attempt} "
        f"spec_version: {spec_version}\n"
        "# Generated by TrainPilot-Local from TrainingSpec; never patch by hand.\n"
    )
    return header + yaml.safe_dump(spec.model_dump(), sort_keys=True)


def render_final_report(context: dict) -> str:
    template = _env.get_template("final_report.md.j2")
    return template.render(**context)


def make_generated_file(path: str, content: str, spec: TrainingSpec) -> GeneratedFile:
    return GeneratedFile(path=path, content=content, spec_hash=spec.spec_hash())
